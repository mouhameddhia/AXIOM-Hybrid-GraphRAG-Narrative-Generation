DEFAULT_OUT = PROJECT_ROOT / "data" / "track_a_sample_payloads.json"
ENGINE_VERSION = "trackA-provisional-0.1"
LEVEL_STEP = "level"

PROVENANCE = (
    "PROVISIONAL STAND-IN -- NOT TRACK A OUTPUT. Generated by "
    "scripts/build_sample_payload.py, which simulates the Track A pricing engine "
    "because its real result object does not exist yet (onboarding plan Section 7: "
    "shape agreed Week 2, frozen Week 7). Track B's runtime code in src/narrative "
    "computes NO pricing figure -- it reads every number from this file. The "
    "recommended_price, price_range, confidence, expected_margin_pct and "
    "acceptance_probability below are illustrative values invented for testing. "
    "The waterfall figures and every record_id are derived from real records in "
    "axiom_pricing_module_Knowledge-graph_PoC.json, so citations resolve against "
    "the actual graph. Replace this file when Track A's real payloads arrive."
)


def main(argv: Sequence[str] | None = None) -> int:
    parser = argparse.ArgumentParser(description=__doc__.splitlines()[1])
    parser.add_argument(
        "--line", action="append", dest="lines",
        help="Order line to build a payload for (repeatable)",
    )
    parser.add_argument(
        "--count", type=int,
        help=(
            "Instead of named lines, pick this many automatically, spread "
            "evenly across the distinct waterfall shapes in the graph"
        ),
    )
    parser.add_argument("--out", type=Path, help="Write here instead of stdout")
    parser.add_argument("--verbose", action="store_true")
    args = parser.parse_args(argv)

    setup_logging(logging.INFO if args.verbose else logging.WARNING)
    settings = get_settings()
    graph = build_graph_source(settings).load()
    serializer = RecordSerializer(
        settings.corpus, LabelIdentityPolicy.learn(graph, settings.corpus)
    )

    if args.count:
        lines = _diverse_lines(graph, args.count)
    else:
        lines = args.lines or ["OL000248", "OL000087"]
    payloads = []
    for index, line in enumerate(lines, start=1):
        try:
            payloads.append(_build(graph, serializer, line, index))
        except ValueError as exc:
            print(f"Skipping {line}: {exc}", file=sys.stderr)

    if not payloads:
        print("No payloads could be built.", file=sys.stderr)
        return 1

    document = {
        "_provenance": PROVENANCE,
        "_contract_version": "provisional-0.1",
        "_generated_by": "scripts/build_sample_payload.py",
        "recommendations": payloads,
    }
    text = json.dumps(document, indent=2, ensure_ascii=False) + "\n"

    if args.out:
        args.out.write_text(text, encoding="utf-8")
        print(f"Wrote {len(payloads)} payload(s) to {args.out}")
    else:
        print(text)
    return 0


def _diverse_lines(graph: KnowledgeGraph, count: int) -> list[str]:
    """
    Pick order lines spread across the distinct waterfall shapes present.

    Evaluating a narrative generator on one shape of waterfall proves very
    little: a two-step walk and a four-step walk exercise different prose,
    different citation counts, and different chances for the model to
    misattribute a stage. Round-robining the shapes keeps a small evaluation
    set from silently becoming a single-case test.
    """
    by_shape: dict[tuple[int, int], list[str]] = {}
    for line, comps in _components_by_line(graph).items():
        levels = [c for c in comps if c.properties.get("step_type") == LEVEL_STEP]
        if len(levels) != 1:
            continue
        deductions = [c for c in comps if c.properties.get("step_type") != LEVEL_STEP]
        if not deductions:
            continue
        on = sum(1 for c in deductions if _as_bool(c.properties.get("on_invoice")))
        by_shape.setdefault((on, len(deductions) - on), []).append(line)

    for lines in by_shape.values():
        lines.sort()

    picked: list[str] = []
    shapes = [by_shape[key] for key in sorted(by_shape)]
    depth = 0
    while len(picked) < count and shapes:
        progressed = False
        for lines in shapes:
            if depth < len(lines) and len(picked) < count:
                picked.append(lines[depth])
                progressed = True
        if not progressed:
            break
        depth += 1
    return picked


def _components_by_line(graph: KnowledgeGraph) -> dict[str, list[GraphNode]]:
    grouped: dict[str, list[GraphNode]] = {}
    for node in graph:
        if node.primary_label != "PriceComponent":
            continue
        line = node.properties.get("applies_to_id")
        if isinstance(line, str):
            grouped.setdefault(line, []).append(node)
    return grouped


def _build(
    graph: KnowledgeGraph, serializer: RecordSerializer, line_id: str, index: int
) -> dict:
    """Assemble one payload the way Track A eventually will."""
    components = [
        node
        for node in graph
        if node.primary_label == "PriceComponent"
        and node.properties.get("applies_to_id") == line_id
    ]
    if not components:
        raise ValueError(f"no PriceComponent records apply to {line_id}")

    levels = [n for n in components if n.properties.get("step_type") == LEVEL_STEP]
    if len(levels) != 1:
        raise ValueError(f"expected exactly one {LEVEL_STEP!r} step, found {len(levels)}")

    level = levels[0]
    deductions = sorted(
        (n for n in components if n is not level),
        key=lambda n: (not _as_bool(n.properties.get("on_invoice")),
                       str(n.properties.get("step_name", ""))),
    )

    list_price = round(float(level.properties["amount"]), 2)
    steps = [
        {
            "name": str(n.properties.get("step_name", "unnamed")),
            "amount": round(float(n.properties["amount"]), 2),
            "on_invoice": _as_bool(n.properties.get("on_invoice")),
            "record_id": serializer.record_id(n),
        }
        for n in deductions
    ]
    on_invoice = round(sum(s["amount"] for s in steps if s["on_invoice"]), 2)
    off_invoice = round(sum(s["amount"] for s in steps if not s["on_invoice"]), 2)
    invoice_price = round(list_price + on_invoice, 2)
    pocket_price = round(invoice_price + off_invoice, 2)
    total = round(on_invoice + off_invoice, 2)

    order_line = _find(graph, "OrderLine", order_line_id=line_id)
    product_id = str(order_line.properties.get("product_id", "")) if order_line else ""
    order_id = str(order_line.properties.get("order_id", "")) if order_line else ""
    order = _find(graph, "Order", order_id=order_id) if order_id else None
    customer_id = str(order.properties.get("customer_id", "")) if order else ""
    unit_price = float(order_line.properties.get("unit_price_recorded", 0)) if order_line else 0.0

    # Illustrative engine output. These five figures are invented: a real
    # engine would derive them from cost, elasticity and win/loss history.
    recommended = round(unit_price * 1.018, 2) if unit_price else round(list_price / 100, 2)

    evidence = [
        serializer.record_id(node)
        for node in (
            order_line,
            _find(graph, "SellableProduct", product_id=product_id),
            _find(graph, "ListPricePeriod", product_id=product_id),
            _find(graph, "ProductCostPeriod", product_id=product_id),
            _find(graph, "TradeCustomer", customer_id=customer_id),
        )
        if node is not None
    ]

    return {
        "recommendation_id": f"REC-{index:04d}",
        "product_id": product_id,
        "customer_id": customer_id,
        "order_line_id": line_id,
        "currency_code": str(level.properties.get("currency_code", "SAR")),
        "recommended_price": recommended,
        "price_range": {
            "low": round(recommended * 0.958, 2),
            "high": round(recommended * 1.045, 2),
        },
        # Illustrative and deliberately varied: a set of payloads that all
        # carry the same confidence would not exercise how a narrative reports
        # a weak recommendation differently from a strong one.
        "confidence": _spread(index, (0.78, 0.41, 0.91, 0.55, 0.67)),
        "expected_margin_pct": _spread(index, (32.3, 11.8, 41.0, 8.4, 24.9)),
        "acceptance_probability": _spread(index, (0.64, 0.52, 0.83, 0.38, 0.71)),
        "waterfall": {
            "list_price": list_price,
            "list_price_record_id": serializer.record_id(level),
            "steps": steps,
            "invoice_price": invoice_price,
            "pocket_price": pocket_price,
            "total_deductions": total,
            "erosion_pct": round(abs(total) / list_price * 100, 1) if list_price else 0.0,
        },
        "evidence_record_ids": evidence,
        "engine_version": ENGINE_VERSION,
    }


def _spread(index: int, values: tuple[float, ...]) -> float:
    """Cycle through illustrative values so a payload set is not uniform."""
    return values[(index - 1) % len(values)]


def _find(graph: KnowledgeGraph, label: str, **match) -> GraphNode | None:
    for node in graph:
        if node.primary_label == label and all(
            node.properties.get(key) == value for key, value in match.items()
        ):
            return node
    return None


def _as_bool(value: object) -> bool:
    if isinstance(value, bool):
        return value
    return str(value).strip().lower() == "true"


