"""
Generate provisional Track A payloads. **This script stands in for Track A.**

Track A (Pricing Engine & MLOps, Nourjihen Elabed) owns price recommendations
and the list-to-pocket walk. Its real result object does not exist yet -- per
Section 7 of the onboarding plan the shape is agreed in Week 2 and freezes in
Week 7 -- so Track B needs something contract-shaped to build and test
against in the meantime.

This script is that stand-in, and it is deliberately **outside** ``src/``:

    scripts/build_sample_payload.py   <- simulates the other track (a fixture tool)
    src/narrative/                    <- Track B's real code, which only reads payloads

Nothing in ``src/narrative`` computes a pricing figure. The arithmetic below
is not Track B doing pricing; it is a fixture generator standing in for a
system that will later do it properly. When Track A's real payloads arrive,
this script is deleted and ``data/track_a_sample_payloads.json`` is replaced.

Why derive the numbers from the graph at all, rather than typing them?
Because the citation path has to be real. Every ``record_id`` in the output
resolves against ``axiom_pricing_module_Knowledge-graph_PoC.json``, so a
narrative generated from these payloads cites records that genuinely exist
and can be looked up. The *figures* are a stand-in; the *evidence* is not.

    python scripts/build_sample_payload.py                   # print to stdout
    python scripts/build_sample_payload.py --line OL000248
    python scripts/build_sample_payload.py --out data/track_a_sample_payloads.json
"""
